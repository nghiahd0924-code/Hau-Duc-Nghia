// ====================================================================================
export function getRandomEssayPrompt(grade: GradeLevel = 6, excludeTopicKey?: string): EssayPromptDetails {
  // Lấy danh sách đề bài trực tiếp từ đúng khối lớp đã chọn
  const pool = ESSAY_PROMPTS_BY_GRADE[grade] || ESSAY_PROMPTS_BY_GRADE[6];
  const candidates = pool.filter((p) => p.topicKey !== excludeTopicKey);
  const activePool = candidates.length > 0 ? candidates : pool;

  const randomIndex = Math.floor(Math.random() * activePool.length);
  return activePool[randomIndex];
}

// ====================================================================================
// HÀM LẤY QUY ĐỊNH SỐ LƯỢNG CÂU CHUẨN THEO KHỐI LỚP
// - Lớp 1 - 3: 3 đến 6 câu
// - Lớp 4 - 5: 8 đến 10 câu
// - Lớp 6 - 9: trên 15 câu (> 15 câu)
// ====================================================================================
export function getSentenceRequirementsForGrade(grade: GradeLevel): {
  minSentences: number;
  maxSentences?: number;
  label: string;
  isStrictOver15: boolean;
} {
  if (grade >= 1 && grade <= 3) {
    return {
      minSentences: 3,
      maxSentences: 6,
      label: '3 - 6 câu',
      isStrictOver15: false,
    };
  }
  if (grade === 4 || grade === 5) {
    return {
      minSentences: 8,
      maxSentences: 10,
      label: '8 - 10 câu',
      isStrictOver15: false,
    };
  }
  return {
    minSentences: 16,
    label: '> 15 câu (từ 16 câu trở lên)',
    isStrictOver15: true,
  };
}
